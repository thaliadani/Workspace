# Atribuição simples
saldo = 500

# Atribuição de soma
saldo += 100
print(saldo)

# Atribuição de subtração
saldo -= 50
print(saldo)

# Atribuição de divisão
saldo /= 2
print(saldo)

# Atribuição de divisão inteira
saldo //= 2
print(saldo)

# Atribuição de multiplicação
saldo *= 2
print(saldo)

# Atribuição de resto
saldo %= 2
print(saldo)

# Atribuição de potência
saldo **= 2
print(saldo)


