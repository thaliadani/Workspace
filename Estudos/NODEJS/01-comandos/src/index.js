//Comandos CMD
// cd - Muda o diretório atual
// dir - Lista os arquivos e pastas do diretório atual
// mkdir - Cria um novo diretório
// rmdir - Remove um diretório vazio
// del - Remove um arquivo
// copy - Copia um arquivo
// move - Move um arquivo ou diretório
// cls - Limpa a tela do terminal

//Comandos NPM
// npm init - Cria um novo projeto Node.js e gera o arquivo package.json
// npm install <pacote> - Instala um pacote do npm
// npm uninstall <pacote> - Desinstala um pacote do npm
// npm update - Atualiza todos os pacotes do projeto
// npm list - Lista os pacotes instalados no projeto
// npm run <script> - Executa um script definido no package.json
// npm start - Executa o script "start" definido no package.json
// npm test - Executa o script "test" definido no package.json
// npm outdated - Lista os pacotes desatualizados
// npm cache clean --force - Limpa o cache do npm

// Comandos do NodeJS
// node index.js - Executa o arquivo index.js
// node --version - Mostra a versão do Node
// node --help - Mostra os comandos disponíveis do Node
// node -v - Mostra a versão do Node
// node -p "2 + 2" - Executa uma expressão JavaScript e mostra o resultado




